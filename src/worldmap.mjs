export function makeProjection({ width, height, west = -170, east = 180, north = 76, south = -50 }) {
  const sx = width / (east - west);
  const sy = height / (north - south);
  return ([lon, lat]) => [(lon - west) * sx, (north - lat) * sy];
}

export function landPaths(project) {
  return Object.values(LAND).map((ring) =>
    'M' + ring.map((p) => project(p).map((v) => v.toFixed(1)).join(',')).join('L') + 'Z').join('');
}

// Pins that would sit on top of each other are pushed apart a little at a time; a pin that has moved keeps a thin
// leader line back to the true place, so the reader still sees where the story happened.
export function spreadPins(pins, { width, height, radius, rounds = 260 }) {
  const placed = pins.map((p) => ({ ...p, x: p.ax, y: p.ay }));
  const gap = radius * 2 + 1.5;
  for (let r = 0; r < rounds; r++) {
    let moved = false;
    for (let i = 0; i < placed.length; i++) {
      for (let j = i + 1; j < placed.length; j++) {
        const a = placed[i], b = placed[j];
        let dx = b.x - a.x, dy = b.y - a.y;
        let d = Math.hypot(dx, dy);
        if (d >= gap) continue;
        if (d < 0.01) { dx = Math.cos(i + j); dy = Math.sin(i + j); d = 1; }
        const push = (gap - d) / 2 + 0.05;
        a.x -= (dx / d) * push; a.y -= (dy / d) * push;
        b.x += (dx / d) * push; b.y += (dy / d) * push;
        moved = true;
      }
    }
    for (const p of placed) {
      // a weak spring back to the true spot keeps the cluster tight
      p.x += (p.ax - p.x) * 0.02; p.y += (p.ay - p.y) * 0.02;
      p.x = Math.min(width - radius - 1, Math.max(radius + 1, p.x));
      p.y = Math.min(height - radius - 1, Math.max(radius + 1, p.y));
    }
    if (!moved) break;
  }
  return placed;
}
